// categories.js — the word lists of the `ريبلكا` game (src/games/games/replica.js): "a human, an animal, a thing, a
// plant, a country that starts with the letter ...". Every category lists its words by first letter; a word is
// written the usual way (أ إ آ ة ى are fine: the game compares them with normalize() of src/games/engine/text.js,
// which makes أ إ آ → ا, ة → ه, ى → ي and drops the hamza ء) and without the article ال (the game strips it from an
// answer), except a name that starts with it (إلهام). `_` joins the words of a name (عبد_الله = "عبد الله").
// A letter with fewer than MIN_WORDS words is never asked.
// The lists are not the only right answers: a listed word wins at once, a word that is only listed in another
// category never counts, and any other plausible word goes to a vote of the players (replica.js). STOP_WORDS are
// chat words (and the category and letter names) that never go to a vote.

export const MIN_WORDS = 3;

const lines = (text) => Object.fromEntries(text.trim().split('\n').map((line) => {
    const [letter, ...words] = line.trim().split(/\s+/u);
    return [letter, words.map((word) => word.replaceAll('_', ' '))];
}));

