export const NO_REVERSE = new Set(['جملة', 'نعمة', 'جزيرة', 'دجاجة', 'نحلة', 'نملة']);

function pairs(lines) {
    return lines.trim().split('\n').map((line) => {
        const at = line.indexOf(':');
        return [line.slice(0, at).trim(), split(line.slice(at + 1))];
    });
}

